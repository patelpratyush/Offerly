BEGIN;
CREATE SCHEMA offerly;
REVOKE ALL ON SCHEMA offerly FROM PUBLIC;
SET LOCAL search_path TO offerly, pg_catalog;

    CREATE TABLE users(id TEXT PRIMARY KEY,email TEXT UNIQUE NOT NULL,password TEXT NOT NULL,name TEXT NOT NULL,timezone TEXT NOT NULL,stages TEXT NOT NULL);
    CREATE TABLE sessions(token TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,expires BIGINT NOT NULL,last_seen BIGINT NOT NULL);
    CREATE TABLE records(sequence BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,kind TEXT NOT NULL,data TEXT NOT NULL,version BIGINT NOT NULL DEFAULT 1);
    CREATE INDEX records_owner ON records(user_id,kind);
    CREATE TABLE events(sequence BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,record_id TEXT NOT NULL,at TEXT NOT NULL,before_data TEXT,after_data TEXT NOT NULL,actor TEXT NOT NULL);
    CREATE INDEX events_owner ON events(user_id,record_id,at);
    CREATE TABLE import_batches(id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,rows TEXT NOT NULL,expires BIGINT NOT NULL,result TEXT,decisions TEXT);
    CREATE TABLE files(id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,name TEXT NOT NULL,mime TEXT NOT NULL,hash TEXT NOT NULL,body BYTEA NOT NULL,created_at TEXT NOT NULL,scanned_at TEXT);

CREATE TABLE rate_limits(key TEXT PRIMARY KEY,count BIGINT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE mutation_receipts(user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,operation_id TEXT NOT NULL,fingerprint TEXT NOT NULL,result TEXT NOT NULL,expires BIGINT NOT NULL,PRIMARY KEY(user_id,operation_id));
CREATE INDEX mutation_expiry ON mutation_receipts(expires);
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE users FROM PUBLIC;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE sessions FROM PUBLIC;
ALTER TABLE records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE records FROM PUBLIC;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE events FROM PUBLIC;
ALTER TABLE import_batches ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE import_batches FROM PUBLIC;
ALTER TABLE files ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE files FROM PUBLIC;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE rate_limits FROM PUBLIC;
ALTER TABLE mutation_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE mutation_receipts FROM PUBLIC;
COMMIT;
